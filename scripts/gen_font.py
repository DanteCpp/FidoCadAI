lines.append("")
lines.append("typedef struct { int8_t left, right; uint16_t off; uint8_t n; } FcStrokeGlyph;")
lines.append("")

blob = []
meta = []  # (ch, left, right, off, n)

def add_char(ch):
    global blob
    strokes, adv, lpad = FONT.get(ch, ([[(0,0),(4,12)],[(4,12),(8,0)]], None, None))
    # missing -> simple diamond as '?'
    if ch not in FONT:
        strokes, adv, lpad = FONT['?']
    left, right, body = emit_glyph(ch, strokes, adv, lpad)
    off = len(blob)
    blob.extend(body)
    meta.append((ch, left, right, off, len(body)))

for ch in order:
    add_char(ch)

# extras start at index 95
extra_index = {}
for ch in extras:
    extra_index[ch] = len(meta)
    add_char(ch)

lines.append("static const int8_t fc_stroke_xy[] = {")
row = []
for i, v in enumerate(blob):
    row.append(str(v))
    if len(row) == 24:
        lines.append("    " + ", ".join(row) + ",")
        row = []
