def emit_glyph(ch, strokes, adv, lpad):
    xs = [x for st in strokes for x, y in st]
    ys = [y for st in strokes for x, y in st]
    if not xs:
        left = 0
        right = adv if adv is not None else 5
        body = []
    else:
        minx, maxx = min(xs), max(xs)
        left = (minx - 1) if lpad is None else lpad
        right = (maxx + 1) if adv is None else (left + adv)
        body = []
        for st in strokes:
            if body:
                body.append(127)
                body.append(127)
            for x, y in st:
                body.extend([int(round(x)), int(round(y))])
    # clamp
    left = max(-20, min(20, int(round(left))))
    right = max(left + 1, min(40, int(round(right))))
    return left, right, body

# Build ASCII 32-126 plus a few extras
order = [chr(c) for c in range(32, 127)]
extras = ['¿', '¡', '°']

lines = []
